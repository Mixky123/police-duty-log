def run_seed():
    """เติมข้อมูลตัวอย่างทั้งหมดลงฐานข้อมูล"""
    db.init_database()

    # 1) เพิ่มเจ้าหน้าที่ และเก็บ id ที่ได้จริงไว้ใช้อ้างอิง
    print("กำลังเพิ่มข้อมูลเจ้าหน้าที่...")
    for rank, name, badge, phone, station in SAMPLE_OFFICERS:
        ok, msg = db.add_officer(rank, name, badge, phone, station)
        print("  -", name, "->", msg)

    # ดึงรายชื่อเจ้าหน้าที่จริงมา map ตามลำดับ index
    officers = db.get_all_officers()
    officer_ids = [o["id"] for o in officers]

    # 2) เพิ่มตารางเวร โดยอ้างอิง officer_id จริง
    print("กำลังเพิ่มตารางเวร...")
    for idx, date, shift, loc, status, note in SAMPLE_DUTIES:
        if idx < len(officer_ids):
            ok, msg = db.add_duty(officer_ids[idx], date, shift, loc, status, note)
            print("  -", date, shift, "->", msg)

    # 3) เพิ่มเหตุการณ์ โดยอ้างอิง officer_id จริง
    print("กำลังเพิ่มบันทึกเหตุการณ์...")
    for time_str, cat, sev, loc, desc, idx in SAMPLE_INCIDENTS:
        officer_id = officer_ids[idx] if idx < len(officer_ids) else None
        ok, msg = db.add_incident(time_str, cat, sev, loc, desc, officer_id)
        print("  -", cat, "->", msg)

    print("\nเติมข้อมูลตัวอย่างเรียบร้อยแล้ว")
    print("เจ้าหน้าที่:", len(db.get_all_officers()), "นาย")
    print("ตารางเวร:", len(db.get_all_duties()), "รายการ")
    print("เหตุการณ์:", len(db.get_all_incidents()), "รายการ")


if __name__ == "__main__":
    run_seed()
